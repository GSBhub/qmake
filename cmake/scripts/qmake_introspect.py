#!/usr/bin/env python3
"""Derive out-of-tree compile flags from a configured QEMU build.

Reads the meson-generated compile_commands.json from a QEMU build directory and
emits a CMake include file defining the include dirs / defines / forced includes
that the qmake feature modules (qmake::osdep, qmake::qapi, qmake::target-<arch>)
need. compile_commands.json is part of meson's introspection output and carries
the complete, resolved command line, which `meson introspect --targets` alone
does not (it omits global project args).

Usage: qmake_introspect.py <qemu-build-dir> <output.cmake>
"""
import json
import os
import shlex
import sys


def parse_entry(entry):
    """Return (include_dirs, defines, forced_includes) resolved to abs paths."""
    toks = shlex.split(entry["command"])
    cwd = entry["directory"]
    includes, defines, forced = [], [], []
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.startswith("-I"):
            p = t[2:] if len(t) > 2 else toks[(i := i + 1)]
            includes.append(p)
        elif t == "-iquote":
            includes.append(toks[(i := i + 1)])
        elif t.startswith("-D"):
            defines.append(t[2:])
        elif t == "-include":
            forced.append(toks[(i := i + 1)])
        i += 1
    # Resolve relative include dirs against the compile cwd (the build dir).
    res = []
    for p in includes:
        if not p:
            continue
        ap = p if os.path.isabs(p) else os.path.normpath(os.path.join(cwd, p))
        if ap not in res:
            res.append(ap)
    return res, defines, forced


def pick(cc, predicate):
    for e in cc:
        if predicate(e):
            return e
    return None


def esc(s):
    """Escape a string for safe interpolation inside a CMake "..." literal.

    Per-target defines carry embedded quotes (e.g. CONFIG_TARGET="foo.h"), so
    backslashes and double quotes must be escaped for the generated set() call.
    """
    return s.replace("\\", "\\\\").replace('"', '\\"')


def cmake_list(paths):
    return ";".join(esc(p) for p in paths)


def cmake_defs(defs):
    return ";".join(esc(d) for d in defs)


def main():
    build_dir, out_path = sys.argv[1], sys.argv[2]
    cc = json.load(open(os.path.join(build_dir, "compile_commands.json")))

    # Representative system (non-per-target) translation unit.
    sysf = pick(cc, lambda e: "COMPILING_PER_TARGET" not in e["command"]
                and "/hw/" in e["file"] and e["file"].endswith(".c"))
    if sysf is None:
        sysf = pick(cc, lambda e: e["file"].endswith(".c"))
    sys_inc, sys_def, sys_forced = parse_entry(sysf)

    lines = [
        "# Generated by qmake_introspect.py from QEMU's compile_commands.json.",
        "# Do not edit by hand; regenerated each CMake configure.",
        f'set(QMAKE_OSDEP_INCLUDE_DIRS "{cmake_list(sys_inc)}")',
        f'set(QMAKE_OSDEP_DEFINES "{cmake_defs(sys_def)}")',
        f'set(QMAKE_OSDEP_FORCED_INCLUDES "{cmake_list(sys_forced)}")',
    ]

    # qapi generated headers live under <build>/qapi; expose explicitly.
    qapi = os.path.join(build_dir, "qapi")
    lines.append(f'set(QMAKE_QAPI_INCLUDE_DIRS "{qapi}")')

    # Per-target (e.g. ARM-only) flags: extra include dirs + defines vs system.
    archs = []
    seen = set()
    for e in cc:
        if "COMPILING_PER_TARGET" not in e["command"]:
            continue
        inc, defs, _ = parse_entry(e)
        # Identify the target by its <arch>-softmmu/.a.p include dir.
        arch = None
        for p in inc:
            base = os.path.basename(p)
            if base.startswith("libqemu-") and "-softmmu" in base:
                arch = base[len("libqemu-"):].split("-softmmu")[0]
                break
        if not arch or arch in seen:
            continue
        seen.add(arch)
        archs.append(arch)
        extra_inc = [p for p in inc if p not in sys_inc]
        extra_def = [d for d in defs if d not in sys_def]
        lines.append(f'set(QMAKE_TARGET_{arch}_INCLUDE_DIRS "{cmake_list(extra_inc)}")')
        lines.append(f'set(QMAKE_TARGET_{arch}_DEFINES "{cmake_defs(extra_def)}")')

    lines.append(f'set(QMAKE_INTROSPECTED_ARCHS "{";".join(archs)}")')
    lines.append("set(QMAKE_INTROSPECTION_OK TRUE)")

    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"qmake_introspect: wrote {out_path} "
          f"(osdep includes={len(sys_inc)}, archs={archs})")


if __name__ == "__main__":
    main()
